#!/usr/bin/env python3
"""Apply pilotname/eboot_patch.json ([{file_off, orig_sha1, new_hex}]) to an ELF, verifying the original bytes by hash.
usage: apply_eboot_patch.py in.elf out.elf [patch.json]
(Pilot-name glyph system: lookup tables, keyboard table, ranking defaults, full-width name pool + repointed name
tables. Generated by pilotname/build_eboot.py against the v0.3 EBOOT; already contained in patches/eboot_v041.json.)"""
import os, sys, json
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..')))
from gseed.hashing import apply
src, dst = sys.argv[1], sys.argv[2]
pj = sys.argv[3] if len(sys.argv) > 3 else os.path.join(os.path.dirname(os.path.abspath(__file__)), 'pilotname', 'eboot_patch.json')
d = apply(bytearray(open(src, 'rb').read()), json.load(open(pj)), os.path.basename(pj))
open(dst, 'wb').write(d); print('applied', pj)
